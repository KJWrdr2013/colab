# 1. Band gap 점수 (50점)
# 광촉매의 가시광선 활용 가능성을 고려
def calculate_gap_score(gap):

    if pd.isna(gap):
        return np.nan

    score = 50 * (
        1 - abs(gap - 2.3) / 0.7
    )

    return np.clip(score, 0, 50)


candidates_2nd['gap_score'] = (
    candidates_2nd['band_gap']
    .apply(calculate_gap_score)
)


# 2. Energy above hull 점수 (35점) 해당 물질이 열역학적 안정 상태(Convex Hull)에서 얼마나 떨어져 있는지 상대값
# 낮을수록 열역학적으로 안정한 소재
def calculate_stability_score(e_hull):

    if pd.isna(e_hull):
        return np.nan

    score = 35 * (
        1 - e_hull / 0.05
    )

    return np.clip(score, 0, 35)


candidates_2nd['stability_score'] = (
    candidates_2nd['e_hull']
    .apply(calculate_stability_score)
)


# 3. 안정상 여부 점수 (15점) 해당 물질이 열역학적으로 안정한 상태인지 여부(T/F)
def calculate_stable_score(value):

    if pd.isna(value):
        return np.nan

    return 15 if value else 0


candidates_2nd['stable_score'] = (
    candidates_2nd['is_stable']
    .apply(calculate_stable_score)
)


